/**
 * Returns a localized vehicle object with full Arabic content when lang === 'ar'
 */
export function getLocalizedVehicle(v, lang) {
  if (!v) return v;
  if (lang !== 'ar') return v;
  const ar = ARABIC_VEHICLE_LOCALIZATIONS[v.id];
  if (!ar) return v;

  return {
    ...v,
    name: ar.name || v.name,
    codename: ar.codename || v.codename,
    role: ar.role || v.role,
    planet: ar.planet || v.planet,
    sector: ar.sector || v.sector,
    status: ar.status || v.status,
    tagline: ar.tagline || v.tagline,
    description: ar.description || v.description,
    lastTelemetry: ar.lastTelemetry || v.lastTelemetry,
    agency: ar.agency || v.agency,
    launchDate: ar.launchDate || v.launchDate,
    landingSite: ar.landingSite || v.landingSite,
    distanceTraveled: ar.distanceTraveled || v.distanceTraveled,
    operationalTime: ar.operationalTime || v.operationalTime,
    stats: ar.stats || v.stats,
    hotspots: v.hotspots
      ? v.hotspots.map((h) => {
          const matchingAr = ar.hotspots?.find((item) => item.id === h.id);
          return matchingAr ? { ...h, label: matchingAr.label } : h;
        })
      : v.hotspots,
  };
}
